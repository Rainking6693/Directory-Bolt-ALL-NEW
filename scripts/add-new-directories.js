async function getExistingDirectories() {
  console.log('Fetching existing directories from database...');

  const { data, error } = await supabase
    .from('directories')
    .select('name, website, submission_url');

  if (error) {
    console.error('Error fetching existing directories:', error.message);
    return [];
  }

  console.log(`Found ${data?.length || 0} existing directories`);
  return data || [];
}

async function insertDirectoriesBatch(directories, batchNumber) {
  console.log(`\nInserting batch ${batchNumber} (${directories.length} directories)...`);

  const { data, error } = await supabase
    .from('directories')
    .insert(directories)
    .select();

  if (error) {
    console.error(`Error inserting batch ${batchNumber}:`, error.message);
    return { success: 0, failed: directories.length, error: error.message };
  }

  console.log(`Batch ${batchNumber}: Successfully inserted ${data?.length || 0} directories`);
  return { success: data?.length || 0, failed: 0 };
}

async function main() {
  console.log('='.repeat(60));
  console.log('Starting Directory Import Process');
  console.log('='.repeat(60));

  // Get existing directories
  const existing = await getExistingDirectories();
  const existingNames = new Set(existing.map(d => d.name?.toLowerCase()));
  const existingWebsites = new Set(existing.map(d => d.website?.toLowerCase()));

  // Filter out duplicates
  const uniqueDirectories = newDirectories.filter(dir => {
    const nameExists = existingNames.has(dir.name.toLowerCase());
    const websiteExists = existingWebsites.has(dir.website.toLowerCase());

    if (nameExists || websiteExists) {
      console.log(`Skipping duplicate: ${dir.name}`);
      return false;
    }
    return true;
  });

  console.log(`\nTotal new directories to add: ${uniqueDirectories.length}`);
  console.log(`Duplicates skipped: ${newDirectories.length - uniqueDirectories.length}`);

  if (uniqueDirectories.length === 0) {
    console.log('\nNo new directories to add. All directories already exist in database.');
    return;
  }

  // Insert in batches of 25
  const BATCH_SIZE = 25;
  let totalSuccess = 0;
  let totalFailed = 0;

  for (let i = 0; i < uniqueDirectories.length; i += BATCH_SIZE) {
    const batch = uniqueDirectories.slice(i, i + BATCH_SIZE);
    const batchNumber = Math.floor(i / BATCH_SIZE) + 1;

    const result = await insertDirectoriesBatch(batch, batchNumber);
    totalSuccess += result.success;
    totalFailed += result.failed;

    // Small delay between batches
    if (i + BATCH_SIZE < uniqueDirectories.length) {
      await new Promise(resolve => setTimeout(resolve, 500));
    }
  }

  console.log('\n' + '='.repeat(60));
  console.log('IMPORT COMPLETE');
  console.log('='.repeat(60));
  console.log(`Successfully added: ${totalSuccess} directories`);
  console.log(`Failed: ${totalFailed} directories`);
  console.log(`Total in database: ${existing.length + totalSuccess} directories`);
}

